const STORAGE_KEY = "language";

i18n.use(initReactI18next).init({
  resources,
  lng: localStorage.getItem(STORAGE_KEY) ?? "ru",
  fallbackLng: "ru",
  interpolation: { escapeValue: false },
});

export function setLanguage(lng: "ru" | "en" | "zh") {
  // A full reload (rather than relying on react-i18next's reactive
  // re-render) guarantees every component picks up the new language
  // immediately and consistently — including anything that computed a
  // translated string once and stashed it in state rather than calling
  // t() on every render.
  localStorage.setItem(STORAGE_KEY, lng);
  window.location.reload();
}

export default i18n;
